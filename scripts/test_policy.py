import unittest
from policy import classify

class PolicyTests(unittest.TestCase):
    def test_empty_task_is_invalid(self): self.assertEqual(classify({})[0], "C")
    def test_known_empty_paths_is_low_risk(self): self.assertEqual(classify({"paths": []})[0], "A")
    def test_unknown_task_field_is_invalid(self): self.assertEqual(classify({"scope":"small"})[0], "C")
    def test_non_string_task_field_is_invalid(self): self.assertEqual(classify({1:"unknown"})[0], "C")
    def test_malformed_cost_ratio_is_invalid(self): self.assertEqual(classify({"cost_ratio":"low"})[0], "C")
    def test_malformed_retry_is_invalid(self): self.assertEqual(classify({"retry":"0"})[0], "C")
    def test_malformed_files_count_is_invalid(self): self.assertEqual(classify({"files_touched":None, "diff_lines":"1"})[0], "C")
    def test_non_finite_diff_lines_is_invalid(self): self.assertEqual(classify({"diff_lines":float("inf")})[0], "C")
    def test_migrations(self): self.assertEqual(classify({"paths":["db/migrations/1.sql"]})[0], "C")
    def test_auth(self): self.assertEqual(classify({"paths":["src/auth/login.py"]})[0], "C")
    def test_workflow(self): self.assertEqual(classify({"paths":[".github/workflows/ci.yml"]})[0], "C")
    def test_env(self): self.assertEqual(classify({"paths":[".env.local"]})[0], "C")
    def test_crypto(self): self.assertEqual(classify({"paths":["keys.crypto.pem"]})[0], "C")
    def test_irreversible(self): self.assertEqual(classify({"irreversible":True})[0], "C")
    def test_money(self): self.assertEqual(classify({"money":True})[0], "C")
    def test_external(self): self.assertEqual(classify({"external_submission":True})[0], "C")
    def test_major_dep(self): self.assertEqual(classify({"major_dependency_change":True})[0], "C")
    def test_license(self): self.assertEqual(classify({"license_change":True})[0], "C")
    def test_scope(self): self.assertEqual(classify({"scope_expansion":True})[0], "C")
    def test_diff_threshold(self): self.assertEqual(classify({"diff_lines":801})[0], "C")
    def test_dependency(self): self.assertEqual(classify({"new_dependency":True})[0], "B")
    def test_schema(self): self.assertEqual(classify({"reversible_schema_change":True})[0], "B")
    def test_api(self): self.assertEqual(classify({"public_api_change":True})[0], "B")
    def test_retry(self): self.assertEqual(classify({"retry":2})[0], "B")
    def test_files(self): self.assertEqual(classify({"files_touched":16})[0], "B")
    def test_cost_b(self): self.assertEqual(classify({"cost_ratio":1.1})[0], "B")
    def test_cost_c(self): self.assertEqual(classify({"cost_ratio":2.1})[0], "C")
    def test_precedence(self): self.assertEqual(classify({"new_dependency":True,"money":True})[0], "C")
    def test_bad_path_fails_closed(self): self.assertEqual(classify({"paths":"x"})[0], "C")
    def test_nested_workflow(self): self.assertEqual(classify({"paths":["repo/.github/workflows/ci.yml"]})[0], "C")
    def test_windows_workflow(self): self.assertEqual(classify({"paths":[r"repo\.github\workflows\ci.yml"]})[0], "C")
    def test_negative_lines(self): self.assertEqual(classify({"diff_lines":-1})[0], "C")
    def test_negative_files(self): self.assertEqual(classify({"files_touched":-1})[0], "C")
    def test_negative_retries(self): self.assertEqual(classify({"retry":-1})[0], "C")
    def test_negative_cost(self): self.assertEqual(classify({"cost_ratio":-0.1})[0], "C")
    def test_nan_cost(self): self.assertEqual(classify({"cost_ratio":float("nan")})[0], "C")
    def test_infinite_cost(self): self.assertEqual(classify({"cost_ratio":float("inf")})[0], "C")
    def test_huge_integer_cost(self): self.assertEqual(classify({"cost_ratio":10**1000})[0], "C")
    def test_wrong_boolean_type(self): self.assertEqual(classify({"scope_expansion":"true"})[0], "C")

if __name__ == "__main__": unittest.main()
